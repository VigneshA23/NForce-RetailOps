-- One cash entry per store per business day (Phase 3), plus an append-only
-- trail of the prior values every time it is re-saved.
-- Owner/Admin is a users row; Super Admin is not (super_admins, no FK to
-- users), so every actor column is a user/super-admin pair of which exactly
-- one is set (same shape as stock_check_corrections, V83).
CREATE TABLE daily_cash_entries (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id                     BIGINT         NOT NULL REFERENCES stores(id),
    business_date                DATE           NOT NULL,
    total_cash_sales             NUMERIC(12,2)  NOT NULL,
    opening_drawer_cash          NUMERIC(12,2)  NOT NULL,
    cash_removed                 NUMERIC(12,2)  NOT NULL,
    cash_remaining               NUMERIC(12,2)  NOT NULL,
    cash_expenses                NUMERIC(12,2)  NOT NULL,
    bank_deposits                NUMERIC(12,2)  NOT NULL,
    other_adjustments            NUMERIC(12,2)  NOT NULL,
    entered_by_user_id           BIGINT         REFERENCES users(id),
    entered_by_super_admin_id    BIGINT         REFERENCES super_admins(super_admin_id),
    entered_at                   TIMESTAMPTZ    NOT NULL,
    updated_by_user_id           BIGINT         REFERENCES users(id),
    updated_by_super_admin_id    BIGINT         REFERENCES super_admins(super_admin_id),
    updated_at                   TIMESTAMPTZ    NOT NULL,
    CONSTRAINT uq_daily_cash_entries_store_date UNIQUE (store_id, business_date),
    CONSTRAINT chk_daily_cash_entries_non_negative CHECK (
        total_cash_sales >= 0 AND opening_drawer_cash >= 0 AND cash_removed >= 0
        AND cash_remaining >= 0 AND cash_expenses >= 0 AND bank_deposits >= 0),
    CONSTRAINT chk_daily_cash_entries_entered_by CHECK (
        (entered_by_user_id IS NULL) <> (entered_by_super_admin_id IS NULL)),
    CONSTRAINT chk_daily_cash_entries_updated_by CHECK (
        (updated_by_user_id IS NULL) <> (updated_by_super_admin_id IS NULL))
);

CREATE TABLE daily_cash_entry_corrections (
    id                                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_cash_entry_id                BIGINT         NOT NULL REFERENCES daily_cash_entries(id),
    previous_total_cash_sales          NUMERIC(12,2)  NOT NULL,
    previous_opening_drawer_cash       NUMERIC(12,2)  NOT NULL,
    previous_cash_removed              NUMERIC(12,2)  NOT NULL,
    previous_cash_remaining            NUMERIC(12,2)  NOT NULL,
    previous_cash_expenses             NUMERIC(12,2)  NOT NULL,
    previous_bank_deposits             NUMERIC(12,2)  NOT NULL,
    previous_other_adjustments         NUMERIC(12,2)  NOT NULL,
    previous_updated_by_user_id        BIGINT         REFERENCES users(id),
    previous_updated_by_super_admin_id BIGINT         REFERENCES super_admins(super_admin_id),
    previous_updated_at                TIMESTAMPTZ    NOT NULL,
    corrected_by_user_id               BIGINT         REFERENCES users(id),
    corrected_by_super_admin_id        BIGINT         REFERENCES super_admins(super_admin_id),
    corrected_at                       TIMESTAMPTZ    NOT NULL,
    CONSTRAINT chk_daily_cash_corrections_prev_by CHECK (
        (previous_updated_by_user_id IS NULL) <> (previous_updated_by_super_admin_id IS NULL)),
    CONSTRAINT chk_daily_cash_corrections_by CHECK (
        (corrected_by_user_id IS NULL) <> (corrected_by_super_admin_id IS NULL))
);

CREATE INDEX idx_daily_cash_entry_corrections_entry ON daily_cash_entry_corrections(daily_cash_entry_id);
CREATE INDEX idx_daily_cash_entries_entered_by ON daily_cash_entries(entered_by_user_id);
CREATE INDEX idx_daily_cash_entries_entered_by_sa ON daily_cash_entries(entered_by_super_admin_id);
CREATE INDEX idx_daily_cash_entries_updated_by ON daily_cash_entries(updated_by_user_id);
CREATE INDEX idx_daily_cash_entries_updated_by_sa ON daily_cash_entries(updated_by_super_admin_id);
