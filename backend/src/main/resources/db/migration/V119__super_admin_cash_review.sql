-- Super Admin cash review: one open flag per entry, an append-only audit of
-- every flag change the Super Admin makes, and the reason attached to each
-- correction they file through the review view.

-- At most one unresolved flag per entry; resolving does not delete the row,
-- it sets resolved_at + resolved_by_super_admin_id, and the partial unique
-- index below lets a later flag start fresh.
CREATE TABLE daily_cash_entry_flags (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_cash_entry_id             BIGINT       NOT NULL REFERENCES daily_cash_entries(id),
    comment                         TEXT         NOT NULL,
    notified_user_id                BIGINT       REFERENCES users(id),
    flagged_by_super_admin_id       BIGINT       NOT NULL REFERENCES super_admins(super_admin_id),
    flagged_at                      TIMESTAMPTZ  NOT NULL,
    comment_updated_at              TIMESTAMPTZ,
    resolved_by_super_admin_id      BIGINT       REFERENCES super_admins(super_admin_id),
    resolved_at                     TIMESTAMPTZ,
    CONSTRAINT chk_daily_cash_flags_resolved_pair CHECK (
        (resolved_at IS NULL) = (resolved_by_super_admin_id IS NULL))
);

CREATE UNIQUE INDEX uq_daily_cash_entry_flags_one_open
    ON daily_cash_entry_flags(daily_cash_entry_id)
    WHERE resolved_at IS NULL;

CREATE INDEX idx_daily_cash_entry_flags_entry ON daily_cash_entry_flags(daily_cash_entry_id);

-- Append-only history of every flag action the Super Admin takes: raise,
-- edit the comment, remove the flag, or resolve-via-correction. Separate
-- from daily_cash_entry_corrections because a flag is not a value change.
CREATE TABLE daily_cash_entry_flag_history (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_cash_entry_id             BIGINT       NOT NULL REFERENCES daily_cash_entries(id),
    flag_id                         BIGINT       REFERENCES daily_cash_entry_flags(id),
    action                          VARCHAR(20)  NOT NULL,
    previous_comment                TEXT,
    new_comment                     TEXT,
    actor_super_admin_id            BIGINT       NOT NULL REFERENCES super_admins(super_admin_id),
    recorded_at                     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT chk_daily_cash_flag_history_action CHECK (
        action IN ('RAISED','COMMENT_EDITED','REMOVED','RESOLVED'))
);

CREATE INDEX idx_daily_cash_entry_flag_history_entry ON daily_cash_entry_flag_history(daily_cash_entry_id);

