-- Per-store target cash-drawer amount (Phase 3, feeds Expected Cash on Hand
-- and month-end variance). One row per store. The $150 operational default
-- lives here, in the column default -- not in application code -- so a store
-- with no explicit change reads 150.00. Rows are created lazily for stores
-- added later; existing stores are backfilled below.
CREATE TABLE store_cash_targets (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id                  BIGINT         NOT NULL REFERENCES stores(id),
    target_amount             NUMERIC(12,2)  NOT NULL DEFAULT 150.00,
    updated_by_user_id        BIGINT         REFERENCES users(id),
    updated_by_super_admin_id BIGINT         REFERENCES super_admins(super_admin_id),
    updated_at                TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_store_cash_targets_store UNIQUE (store_id),
    CONSTRAINT chk_store_cash_targets_non_negative CHECK (target_amount >= 0),
    -- Both null = still the untouched default; never both set.
    CONSTRAINT chk_store_cash_targets_updated_by CHECK (
        updated_by_user_id IS NULL OR updated_by_super_admin_id IS NULL)
);

-- Append-only trail: one row per explicit change. Exactly one actor is set
-- (Owner/Admin is a users row; Super Admin is not -- same shape as
-- stock_check_corrections, V83).
CREATE TABLE store_cash_target_changes (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id                  BIGINT         NOT NULL REFERENCES stores(id),
    previous_amount           NUMERIC(12,2)  NOT NULL,
    new_amount                NUMERIC(12,2)  NOT NULL,
    changed_by_user_id        BIGINT         REFERENCES users(id),
    changed_by_super_admin_id BIGINT         REFERENCES super_admins(super_admin_id),
    changed_at                TIMESTAMPTZ    NOT NULL,
    CONSTRAINT chk_store_cash_target_changes_non_negative CHECK (new_amount >= 0),
    CONSTRAINT chk_store_cash_target_changes_by CHECK (
        (changed_by_user_id IS NULL) <> (changed_by_super_admin_id IS NULL))
);

CREATE INDEX idx_store_cash_target_changes_store ON store_cash_target_changes(store_id, changed_at);
CREATE INDEX idx_store_cash_targets_updated_by ON store_cash_targets(updated_by_user_id);
CREATE INDEX idx_store_cash_targets_updated_by_sa ON store_cash_targets(updated_by_super_admin_id);
CREATE INDEX idx_store_cash_target_changes_by ON store_cash_target_changes(changed_by_user_id);
CREATE INDEX idx_store_cash_target_changes_by_sa ON store_cash_target_changes(changed_by_super_admin_id);

INSERT INTO store_cash_targets (store_id) SELECT id FROM stores;
